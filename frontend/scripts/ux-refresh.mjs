import assert from "node:assert/strict";
import { pathToFileURL } from "node:url";
import { writeFile, mkdir } from "node:fs/promises";
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE ? pathToFileURL(process.env.PLAYWRIGHT_MODULE).href : "playwright");
const base = "http://127.0.0.1:4173";
const browser = await chromium.launch();
const context = await browser.newContext({ viewport: { width: 1440, height: 1000 }, timezoneId: "America/Sao_Paulo" });
const page = await context.newPage();
const results = [];
const errors = [];
const external = [];
context.on("page", p => p.on("pageerror", e => errors.push(e.message)));
page.on("pageerror", e => errors.push(e.message));
context.on("request", r => { if (!r.url().startsWith(base)) external.push(r.url()); });
const check = (name, condition) => { assert(condition, name); results.push({ name, passed: true }); console.log("PASS", name); };
await mkdir("test-results/refresh", { recursive: true });
await page.goto(base);
await page.getByRole("heading", { level: 1 }).waitFor();
await page.evaluate(() => document.fonts.ready);
check("Âncoras internas apontam para seções existentes", await page.evaluate(() => [...document.querySelectorAll('a[href^="#"]')].every(a => a.hash.length > 1 && document.getElementById(a.hash.slice(1)))));
check("FAQ apresenta seis respostas sem interação adicional", await page.locator(".landing-faq article").count() === 6);
await page.screenshot({ path: "test-results/refresh/home-desktop.png" });
await page.locator(".landing-footer").screenshot({ path: "test-results/refresh/footer-desktop.png" });
for (const [name, widths] of [["clinic-room", [480, 800, 1200]], ["clinic-detail", [400, 800]]]) {
  for (const width of widths) {
    const response = await page.request.get(`${base}/images/${name}-${width}.webp`);
    const body = await response.body();
    check(`${name}-${width}: WebP servido abaixo de 300 KB`, response.status() === 200 && response.headers()["content-type"] === "image/webp" && body.length < 300000 && body.subarray(8, 12).toString() === "WEBP");
  }
}
await page.locator(".landing-about-photo").scrollIntoViewIfNeeded();
await page.waitForFunction(() => [...document.querySelectorAll("main img")].every(img => img.complete && img.naturalWidth > 0));
check("Fotos carregadas, dimensionadas e com descrição", await page.locator("main img").evaluateAll(imgs => imgs.every(i => i.getAttribute("alt") && i.getAttribute("width") && i.getAttribute("height"))));
await page.screenshot({ path: "test-results/refresh/home-full-desktop.png", fullPage: true });
await page.setViewportSize({ width: 375, height: 900 });
await page.screenshot({ path: "test-results/refresh/home-mobile.png", fullPage: true });
await page.locator(".landing-footer").screenshot({ path: "test-results/refresh/footer-mobile.png" });
await page.goto(base + "/agendar/demonstracao");
await page.getByRole("combobox", { name: "Avaliação / procedimento", exact: true }).selectOption("demo-evaluation");
await page.getByRole("combobox", { name: "Profissional", exact: true }).selectOption("demo-pro-1");
const tomorrow = new Date(); tomorrow.setDate(tomorrow.getDate() + 1);
const day = new Intl.DateTimeFormat("en-CA", { timeZone: "America/Sao_Paulo", year: "numeric", month: "2-digit", day: "2-digit" }).format(tomorrow);
await page.getByLabel("Data", { exact: true }).fill(day);
await page.getByRole("radio").first().check();
await page.getByLabel("Nome completo", { exact: true }).fill("Pessoa Exemplo");
await page.getByLabel("Telefone de contato", { exact: true }).fill("00000000000");
await page.getByLabel("E-mail (opcional)").fill("teste@example.invalid");
for (const [action, field] of [["Alterar horário", "Data"], ["Alterar dados", "Nome completo"], ["Alterar consulta", "Avaliação / procedimento"]]) {
  await page.getByRole("button", { name: "Revisar solicitação", exact: true }).click();
  await page.getByRole("button", { name: action, exact: true }).click();
  const target = field === "Avaliação / procedimento" ? page.getByRole("combobox", { name: field, exact: true }) : page.getByLabel(field, { exact: true });
  check(`${action} leva foco ao campo correspondente`, await target.evaluate(el => el === document.activeElement));
  check(`${action} preserva identificação e horário`, (await page.getByLabel("Nome completo", { exact: true }).inputValue()) === "Pessoa Exemplo" && await page.getByRole("radio").first().isChecked());
}
await page.getByRole("button", { name: "Revisar solicitação", exact: true }).click();
await page.screenshot({ path: "test-results/refresh/booking-review-mobile.png", fullPage: true });
const popupPromise = context.waitForEvent("page");
await page.getByRole("link", { name: "Consultar dúvidas frequentes (nova aba)" }).click();
const popup = await popupPromise;
await popup.waitForURL("**/#duvidas");
await popup.getByRole("heading", { name: "Dúvidas frequentes.", exact: true }).waitFor();
await popup.waitForFunction(() => { const section = document.getElementById("duvidas"); return section && section.getBoundingClientRect().top >= -2 && section.getBoundingClientRect().top < innerHeight; });
check("Ajuda posiciona a nova aba na seção de dúvidas", true);
check("Ajuda abre FAQ sem perder a revisão", await page.getByRole("heading", { name: "Revise sua solicitação" }).isVisible());
await popup.close();
await page.goto(base + "/agenda");
await page.getByLabel("Ir para data", { exact: true }).fill(day);
await page.locator(".agenda-mobile-filters summary").click();
await page.getByRole("combobox", { name: "Filtrar agenda por dentista" }).selectOption("demo-pro-1");
await page.getByRole("combobox", { name: "Situação", exact: true }).selectOption("PENDING");
await page.getByRole("group", { name: "Período da agenda" }).getByRole("button", { name: "Semana", exact: true }).click();
await page.reload();
await page.getByRole("heading", { name: "Agenda", exact: true }).waitFor();
await page.getByText("Filtros (2)", { exact: true }).click();
check("Reload preserva data, profissional e situação", (await page.getByLabel("Ir para data", { exact: true }).inputValue()) === day && (await page.getByRole("combobox", { name: "Filtrar agenda por dentista" }).inputValue()) === "demo-pro-1" && (await page.getByRole("combobox", { name: "Situação", exact: true }).inputValue()) === "PENDING");
check("Reload preserva período semanal", await page.getByRole("group", { name: "Período da agenda" }).getByRole("button", { name: "Semana", exact: true }).getAttribute("aria-pressed") === "true");
await page.goto(base + "/");
await page.goBack();
await page.getByRole("heading", { name: "Agenda", exact: true }).waitFor();
check("Voltar preserva filtros sem dados pessoais na URL", new URL(page.url()).searchParams.get("status") === "PENDING" && !page.url().includes("Pessoa"));
await page.setViewportSize({ width: 1440, height: 1000 });
await page.getByRole("group", { name: "Visualização da agenda" }).getByRole("button", { name: "Grade semanal", exact: true }).click();
await page.reload();
await page.getByRole("region", { name: "Agenda semanal com rolagem horizontal" }).waitFor();
check("Grade semanal preservada após recarregar", true);
await page.goto(base + "/agenda?date=2026-02-31&status=INVALID&view=week&period=invalid");
await page.getByRole("heading", { name: "Agenda", exact: true }).waitFor();
check("Filtros inválidos não quebram a agenda", (await page.getByLabel("Ir para data", { exact: true }).inputValue()) !== "2026-02-31" && (await page.getByRole("combobox", { name: "Situação", exact: true }).inputValue()) === "");
await page.goto(base + "/agenda");
await page.getByRole("heading", { name: "Agenda", exact: true }).waitFor();
await page.waitForTimeout(600);
await page.screenshot({ path: "test-results/refresh/agenda-desktop.png", fullPage: true });
check("Sem requisições externas no carregamento ou ajuda", external.length === 0);
check("Sem erros de JavaScript", errors.length === 0);
await writeFile("test-results/refresh/results.json", JSON.stringify({ date: new Date().toISOString(), browser: browser.version(), results, errors, external }, null, 2));
await browser.close();
